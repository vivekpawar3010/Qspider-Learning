-- ==============================
-- DATABASE
-- ==============================
DROP DATABASE IF EXISTS zomato_db;
CREATE DATABASE zomato_db;
USE zomato_db;

-- ==============================
-- TABLES
-- ==============================

CREATE TABLE RESTAURANT (
    RESTAURANT_ID INT PRIMARY KEY AUTO_INCREMENT,
    NAME VARCHAR(100) NOT NULL,
    PHONE VARCHAR(15) UNIQUE,
    EMAIL VARCHAR(100) UNIQUE,
    CITY VARCHAR(100) NOT NULL,
    AREA VARCHAR(100) NOT NULL,
    RATING DECIMAL(3,2),
    CREATED_DATE DATETIME DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE CATEGORY (
    CATEGORY_ID INT PRIMARY KEY AUTO_INCREMENT,
    CATEGORY_NAME VARCHAR(100) NOT NULL,
    DESCRIPTION VARCHAR(200)
);

CREATE TABLE RESTAURANT_CATEGORY (
    RESTAURANT_ID INT,
    CATEGORY_ID INT,
    PRIMARY KEY (RESTAURANT_ID, CATEGORY_ID),
    FOREIGN KEY (RESTAURANT_ID) REFERENCES RESTAURANT(RESTAURANT_ID),
    FOREIGN KEY (CATEGORY_ID) REFERENCES CATEGORY(CATEGORY_ID)
);

CREATE TABLE MENU (
    MENU_ID INT PRIMARY KEY AUTO_INCREMENT,
    RESTAURANT_ID INT,
    MENU_NAME VARCHAR(100) NOT NULL,
    CREATED_DATE DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (RESTAURANT_ID) REFERENCES RESTAURANT(RESTAURANT_ID)
);

CREATE TABLE MENU_ITEM (
    ITEM_ID INT PRIMARY KEY AUTO_INCREMENT,
    MENU_ID INT,
    ITEM_NAME VARCHAR(100) NOT NULL,
    PRICE DECIMAL(10,2),
    AVAILABLE_STATUS ENUM('YES','NO') DEFAULT 'YES',
    FOREIGN KEY (MENU_ID) REFERENCES MENU(MENU_ID)
);

CREATE TABLE CUSTOMER (
    CUSTOMER_ID INT PRIMARY KEY AUTO_INCREMENT,
    FULL_NAME VARCHAR(100) NOT NULL,
    PHONE VARCHAR(15) UNIQUE,
    EMAIL VARCHAR(100) UNIQUE,
    GENDER ENUM('M','F','O'),
    REGISTRATION_DATE DATETIME DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE ADDRESS (
    ADDRESS_ID INT PRIMARY KEY AUTO_INCREMENT,
    CUSTOMER_ID INT,
    HOUSE_NO VARCHAR(50),
    STREET VARCHAR(100),
    CITY VARCHAR(100),
    PINCODE VARCHAR(10),
    ADDRESS_TYPE ENUM('HOME','OFFICE','OTHER'),
    FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER(CUSTOMER_ID)
);

CREATE TABLE DELIVERY_PERSON (
    DELIVERY_ID INT PRIMARY KEY AUTO_INCREMENT,
    NAME VARCHAR(100),
    PHONE VARCHAR(15) UNIQUE,
    VEHICLE_NO VARCHAR(20) UNIQUE,
    STATUS ENUM('AVAILABLE','BUSY') DEFAULT 'AVAILABLE'
);

CREATE TABLE ORDERS (
    ORDER_ID INT PRIMARY KEY AUTO_INCREMENT,
    CUSTOMER_ID INT,
    RESTAURANT_ID INT,
    DELIVERY_ID INT UNIQUE,
    ORDER_DATE DATETIME DEFAULT CURRENT_TIMESTAMP,
    TOTAL_AMOUNT DECIMAL(10,2),
    ORDER_STATUS ENUM('PLACED','ONWAY','DELIVERED','CANCELLED'),
    FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER(CUSTOMER_ID),
    FOREIGN KEY (RESTAURANT_ID) REFERENCES RESTAURANT(RESTAURANT_ID),
    FOREIGN KEY (DELIVERY_ID) REFERENCES DELIVERY_PERSON(DELIVERY_ID)
);

CREATE TABLE ORDER_ITEM (
    ORDER_ID INT,
    ITEM_ID INT,
    QUANTITY INT,
    PRICE DECIMAL(10,2),
    PRIMARY KEY (ORDER_ID, ITEM_ID),
    FOREIGN KEY (ORDER_ID) REFERENCES ORDERS(ORDER_ID),
    FOREIGN KEY (ITEM_ID) REFERENCES MENU_ITEM(ITEM_ID)
);

CREATE TABLE PAYMENT (
    PAYMENT_ID INT PRIMARY KEY AUTO_INCREMENT,
    ORDER_ID INT UNIQUE,
    PAYMENT_MODE ENUM('CARD','CASH','UPI'),
    PAYMENT_DATE DATETIME DEFAULT CURRENT_TIMESTAMP,
    AMOUNT DECIMAL(10,2),
    PAYMENT_STATUS ENUM('SUCCESS','FAILED','PENDING'),
    FOREIGN KEY (ORDER_ID) REFERENCES ORDERS(ORDER_ID)
);

CREATE TABLE REVIEW (
    REVIEW_ID INT PRIMARY KEY AUTO_INCREMENT,
    CUSTOMER_ID INT,
    RESTAURANT_ID INT,
    RATING DECIMAL(3,2),
    COMMENTS VARCHAR(200),
    REVIEW_DATE DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER(CUSTOMER_ID),
    FOREIGN KEY (RESTAURANT_ID) REFERENCES RESTAURANT(RESTAURANT_ID)
);

CREATE TABLE COUPON (
    COUPON_ID INT PRIMARY KEY AUTO_INCREMENT,
    CODE VARCHAR(20),
    DISCOUNT_PERCENT DECIMAL(5,2),
    VALID_TILL DATE
);

CREATE TABLE ORDER_COUPON (
    ORDER_ID INT,
    COUPON_ID INT,
    PRIMARY KEY (ORDER_ID, COUPON_ID),
    FOREIGN KEY (ORDER_ID) REFERENCES ORDERS(ORDER_ID),
    FOREIGN KEY (COUPON_ID) REFERENCES COUPON(COUPON_ID)
);

