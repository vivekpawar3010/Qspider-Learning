
-- 1] WAQTD DIFFERENT NAMES OF EMP’S WITH THEIR SALARIES 
-- AND ANNUAL SALARY IF THERE SALARY IS IN THE RANGE OF 
-- 2000 TO 3000 RPS AND THE  ANNUAL SALARY SHOULD EXCEED 
-- 29400 RPS. 
-- ENAME             SAL ANNUAL_SAL
-- ---------- ---------- ----------
-- BLAKE            2850      34200
-- FORD             3000      36000
-- JONES            2975      35700
-- SCOTT            3000      36000

 SELECT DISTINCT ENAME, SAL , SAL * 12 AS ANNUAL_SAL
 FROM EMP
 WHERE (SAL BETWEEN 2000 AND 3000 )AND
 (SAL * 12) > 29400 ;
 
-- 2] WAQTD NAMES OF EMP’S WHO ARE WORKING IN THE 
-- DEPTNO 10,40,30,20 EXCEPT SALESMAN & MANAGER’S & 
-- SHOULD BE HIRED AFTER 1982. 

-- ENAME
-- ----------
-- SCOTT
-- ADAMS

SELECT ENAME FROM EMP
WHERE DEPTNO IN (10, 20 , 30, 40) AND 
JOB NOT IN ('SALESMAN', 'MANAGER') AND 
HIREDATE > '31-DEC-1982';

 
-- 3] WAQTD DETAILS OF EMP’S WITH THEIR HALF_TERM SALARY 
-- IF EMP HIRED IN THE MONTH OF FEBRUARY OR DECEMBER  
-- EXCEPT THE RANGE OF EMPID’S 7369 TO 7521. 
--      EMPNO ENAME      JOB              MGR HIREDATE         SAL       COMM     DEPTNO HALF_TERM_SAL
-- ---------- ---------- --------- ---------- --------- ---------- ---------- ---------- -------------
--       7900 JAMES      CLERK           7698 03-DEC-81        950                    30          5700
--       7902 FORD       ANALYST         7566 03-DEC-81       3000                    20         18000
SELECT EMP.*, SAL*6 AS HALF_TERM_SAL FROM EMP 
WHERE (HIREDATE LIKE '%-FEB-%' OR HIREDATE LIKE '%-DEC%') AND 
EMPNO NOT BETWEEN 7369 AND 7521;
 
-- 4] WAQTD NUMBER OF EMP’S IN EACH DEPTNO IF EMP GOT 
-- HIRED IN THE YEAR 1981, EMP NAME SHOULD BE HAVING 
-- CHAR ‘E’ IN THE NAME. 

--   COUNT(*)     DEPTNO
-- ---------- ----------
--          4         30
--          1         20

    SELECT COUNT(*), DEPTNO
    FROM EMP 
    WHERE HIREDATE LIKE '%-81' AND
    ENAME LIKE '%E%'
    GROUP BY DEPTNO;

 
-- 5] WAQTD NUMBER OF EMP’S, MAXIMUM SALARY, MINIMUM 
-- SALARY , TOTAL SALARY IN EACH DEPTNO IF EMP’S IS NOT 
-- EARNING ANY COMMISSION BUT HAVING MANAGER NUMBER, 
-- & THERE SHOULD BE AT LEAST  2 EMP’S, MAXIMUM SALARY 
-- SHOULD CROSS 2450 RPS, MINIMUM SALARY SHOULD BE 
-- -- EITHER 800 OR 950 RPS WITH 4 OR 5 DIGIT TOTAL SALARY. 
--     DEPTNO   COUNT(*)   MAX(SAL)   MIN(SAL)   SUM(SAL)
-- ---------- ---------- ---------- ---------- ----------
--         20          5       3000        800      10875

SELECT DEPTNO, COUNT(*), MAX(SAL), MIN(SAL), SUM(SAL) FROM EMP
WHERE COMM IS NULL AND MGR IS NOT NULL 
GROUP BY DEPTNO 
HAVING COUNT(*) > 2 AND MAX(SAL) > 2450 AND MIN(SAL) IN (800, 950) AND SUM(SAL) BETWEEN 1000 AND 99999;
 
-- 6] WAQTD NUMBER OF EMP’S IN EACH DESIGNATION IF EMP IS 
-- HAVING CHAR ‘L’ OR  ‘N’ IN THE DESIGNATION WITH AT LEAST 2 
-- EMP’S IN EACH DESIGNATION WITH 4 DIGIT MAXIMUM SALARY 
-- & THE MINIMUM SALARY SHOULD NOT BE IN THE RANGE OF 
-- 100 TO 1000 RPS, AND SORT THE DATA BASED ON 
-- GROUP_BY_EXPRESSION. 

-- JOB       NO_OF_EMPS
-- --------- ----------
-- ANALYST            2
-- MANAGER            3
-- SALESMAN           4


SELECT JOB, COUNT(*) AS NO_OF_EMPS
FROM EMP
WHERE (JOB LIKE '%L%' OR JOB LIKE '%N%')
GROUP BY JOB
HAVING COUNT(*) >= 2 
   AND MAX(SAL) <= 9999
   AND MIN(SAL) NOT BETWEEN 100 AND 1000
ORDER BY JOB;

 
-- 7] WAQTD THE O/P IN THE FOLLOWING FORMAT :  
 
-- MR.ABC YOU HIRED ON XYZ AND WORKING AS A PQR WITH 
-- 23% HIKE OF SALARY HJY 
 
-- [IF EMP HIRED BEFORE 1982 EXCEPT THE MONTH OF 
-- SEPTEMBER 1981, AND EMP SHOULD BE EITHER ‘ANALYST’ OR 
-- ‘PRESIDENT’] 

-- OUTPUT
-- ----------------------------------------------------------------------------------------------------
-- MR.KING YOU HIRED ON 17-NOV-81 AND WORKING AS A PRESIDENT WITH 23% HIKE OF SALARY 6150
-- MR.FORD YOU HIRED ON 03-DEC-81 AND WORKING AS A ANALYST WITH 23% HIKE OF SALARY 3690

 SELECT 'MR.' || ENAME || ' YOU HIRED ON ' || TO_CHAR(HIREDATE, 'DD-MON-YY') || ' AND WORKING AS A ' || JOB || ' WITH 23% HIKE OF SALARY ' || (SAL * 1.23) AS OUTPUT
FROM EMP
WHERE HIREDATE < '01-JAN-1982'
  AND TO_CHAR(HIREDATE, 'MON-YYYY') != 'SEP-1981'
  AND JOB IN ('ANALYST', 'PRESIDENT');


-- 8] WRITE THE NAMES OF EMP’S & SALARY IF EMP IS HAVING 
-- VOWELS IN THE NAME EXC  EPT THE DEPTNO 20 EMP’S & THE 
-- SALARY SHOULD BE AT LEAST 2450 & ATMOST 3000 RPS & 
-- ARRANGE THE DATA BASED ON NAMES IN DESCENDING. 

-- ENAME             SAL
-- ---------- ----------
-- CLARK            2450
-- BLAKE            2850

SELECT ENAME, SAL 
FROM EMP
WHERE (ENAME LIKE '%A%' OR ENAME LIKE '%E%' OR ENAME LIKE '%I%' OR ENAME LIKE '%O%' OR ENAME LIKE '%U%')
  AND DEPTNO != 20
  AND SAL BETWEEN 2450 AND 3000
ORDER BY ENAME DESC;



-- 9] WAQTD MAXIMUM SALARY, MIN SAL, TOTAL SAL & NUMBER 
-- OF EMP’S IN THE EMP TABLE IF EMP IS EARNING SALARY, 
-- NAME SHOULD NOT CONTAIN CHAR ‘S’ & EMP SHOULD BE 
-- WORKING EITHER IN DEPTNO 10 OR 30. 

--    MAX_SAL    MIN_SAL  TOTAL_SAL NO_OF_EMPS
-- ---------- ---------- ---------- ----------
--       5000       1250      17200          8
SELECT MAX(SAL) , MIN(SAL) , SUM(SAL) , COUNT(*) 
FROM EMP
WHERE SAL IS NOT NULL
  AND ENAME NOT LIKE '%S%'
  AND DEPTNO IN (10, 30);


 
-- 10] WAQTD NAME OF THE EMP WHO IS EARNING MORE THAN 
-- 1000 BUT LESS THAN 5000, SHOULD BE HAVING MANAGER 
-- NUMBER IN THE RANGE OF 7000 TO 8000 EXCEPT THE ‘CLERK’ 
-- AND ‘MANAGER’, THE NAME SHOULD BE HAVING CHAR ‘R’ AT 
-- 4TH LAST POSITION & EMP SHOULD BE EARNING COMMISSION 
-- [SORT THE DATA BASED ON SALARY MAXIMUM TO MINIMUM]. 
 
 
--  ENAME
-- ----------
-- MARTIN
SELECT ENAME 
FROM EMP
WHERE SAL > 1000 AND SAL < 5000
  AND MGR BETWEEN 7000 AND 8000
  AND JOB NOT IN ('CLERK', 'MANAGER')
