-- **7] WAQTD NAME, SAL, ANNUAL SAL IF EMP IS NOT WORKING AS SALESMAN OR MANAGER IN DEPTNO 30.**

-- ENAME SAL ANNUAL_SAL

---

-- JAMES 950 11400

SELECT ENAME, SAL, SAL * 12 AS ANNUAL_SAL FROM EMP 
WHERE DEPTNO = 30 AND JOB NOT IN ('SALESMAN', 'MANAGER');

