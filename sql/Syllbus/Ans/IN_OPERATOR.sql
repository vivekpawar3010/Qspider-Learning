-- **6] WAQTD DETAILS OF AN EMP ALONG WITH ANNUAL SALARY IF EMP IS EARNING COMMISSION 300,1400,500.**

-- EMPNO ENAME JOB MGR HIREDATE SAL COMM DEPTNO ANNUAL_SAL

