-- 1] WAQTD DEPARTMENT NAME OF EMP WHOSE DESIGNATION IS PRESIDENT.
SELECT DNAME FROM DEPT
WHERE DEPTNO IN (SELECT DEPTNO FROM EMP WHERE JOB = 'PRESIDENT');


-- 2] WAQTD EMPLOYEE NAME OF EMP WORKING IN ACCOUNTING DEPARTMENT.
SELECT ENAME,SAL FROM EMP 
WHERE DEPTNO IN (SELECT DEPTNO FROM DEPT WHERE DNAME = 'ACCOUNTING');


-- 3] WAQTD EMPLOYEE NAME & SALARY OF EMP'S WHO ARE WORKING IN CHICAGO.
SELECT ENAME, SAL FROM EMP 
WHERE DEPTNO = (SELECT DEPTNO FROM DEPT WHERE LOC = 'CHICAGO');


-- 4] WAQTD DETAILS OF AN EMP WHOSE WORKING IN SALES DEPARTMENT.
SELECT * FORM EMP 
WHERE DEPTNO IN (SELECT DEPTNO FROM EMP WHERE DNAME = 'SALES');


-- 5] WAQTD DETAILS OF EMP ALONG WITH ANNUAL SAL IF EMP'S ARE WORKING IN NEW YORK.
SELECT EMP.*, SAL * 12 AS ANNUAL_SAL FROM EMP
DEPTNO IN (SELECT DEPTNO FROM EMP WHERE LOC = 'NEW YORK');

-- 6] WAQTD EMPLOYEE NAME OF EMP WORKING IN OPERATIONS DEPARTMENT.
SELECT ENAME FROM EMP 
WHERE DEPTNO IN (SELECT DEPTNO FROM DEPT WHERE DNAME = 'OPERATIONS');

-- 7] WAQTD NAME OF EMP EARNING MORE THAN SCOTT IN ACCOUNTING DEPARTMENT.
SELECT ENAME FROM EMP 
WHERE SAL > (SELECT SAL FROM EMP WHERE ENAME = 'SCOTT') AND
DEPTNO IN (SELECT DEPTNO FROM EMP WHERE DNAME = 'ACCOUNTING');


-- 8] WAQTD DETAILS OF EMP WORKING AS MANAGER IN CHICAGO.
SELECT * FROM EMP 
WHERE EMPNO IN (SELECT MGR FROM EMP WHERE DEPTNO IN (SELECT DEPTNO FROM DEPT WHERE DNAME = 'CHICAGO'));


-- 9] WAQTD NAME & SALARY OF EMP'S EARNING MORE THAN KING IN ACCOUNTING DEPARTMENT.
SELECT ENAME,SAL FROM EMP
WHERE SAL > (SELECT SAL FROM EMP WHERE ENAME = 'KING') AND 
DEPTNO IN (SELECT DEPTNO FROM DEPT WHERE DNAME = 'ACCOUNTING');


-- 10] WAQTD DETAILS OF EMP WHO IS WORKING AS SALESMAN IN SALES DEPARTMENT.
SELECT * FROM EMP 
WHERE JOB = 'SALESMAN' AND 
DEPTNO IN ( SELECT DEPTNO FROM DEPT WHERE DNAME = 'SALES');

-- 11] WAQTD NAME, SAL, JOB, HIREDATE OF EMP'S WORKING IN OPERATION DEPARTMENT.
SELECT ENAME, SAL, JOB , HIREDATE FROM EMP
WHERE DEPTNO IN (SELECT DEPTNO FROM EMP WHERE DNAME = 'OPERATION');
-- 12] WAQTD ALL THE EMP'S WHOSE DEPARTMENT NAME ENDING WITH 'S'.
SELECT * FROM EMP 
WHERE DEPTNO IN (SELECT DEPTNO FROM DEPT WHERE DNAME LIKE '%S');



-- 13] WAQTD DEPARTMENT NAME OF EMP'S WHOSE SAL IS 800.
SELECT DNAME FROM DEPT
WHERE DEPTNO IN (SELECT DEPTNO FROM EMP WHERE SAL = 800);

-- 14] WAQTD DNAME & LOC OF EMP'S WHOSE NAME HAS CHARACTER 'A' IN IT.
SELECT DNAME, LOC FROM DEPT
WHERE DEPTNO IN (SELECT DEPTNO FROM EMP WHERE ENAME LIKE '%A%');


-- 15] WAQTD DEPT NAME OF AN EMP WHO EARNS COMMISSION.
SELECT DNAME FROM DEPT
WHERE DEPTNO IN (SELECT DEPTNO FROM EMP WHERE COMM IS NOT NULL);


-- 16] WAQTD LOC OF EMP IF THEY EARN COMMISSION IN DEPARTMENT NUMBER 40.
SELECT LOC FROM DEPT
WHERE DEPTNO IN (SELECT DEPTNO FROM EMP WHERE COMM IS NOT NULL AND DEPTNO IN (40));


-- 17] WAQTD NAME OF THE EMP EARNING MAX SAL.

SELECT ENAME FROM EMP
WHERE SAL IN (SELECT MAX(SAL) FROM EMP);