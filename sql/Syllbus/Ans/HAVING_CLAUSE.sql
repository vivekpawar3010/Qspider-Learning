HAVING COUNT(*) >= 4;


-- ### 3] WAQTD NUMBER OF EMP'S EARNING MORE THAN 1200 IN EACH JOB & THE TOTAL SAL NEEDED TO PAY IN EACH JOB MUST EXCEED 3800.
-- Expected Output:
-- | COUNT(*) | JOB       |
-- | 4        | SALESMAN  |
-- | 1        | PRESIDENT |
