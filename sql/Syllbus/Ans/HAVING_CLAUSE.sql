-- ### 1] WAQTD NUMBER OF EMP'S WORKING IN EACH DEPT IF THERE ARE ATLEAST 2 EMP'S WORKING IN EACH DEPT.
-- Expected Output:
-- | COUNT(*) | DEPTNO |
-- | 6        | 30     |
-- | 5        | 20     |
-- | 3        | 10     |
SELECT COUNT(*), DEPTNO 
FROM EMP
GROUP BY DEPTNO
HAVING COUNT(*) >= 2;


